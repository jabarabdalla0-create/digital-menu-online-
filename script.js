let currentLang = localStorage.getItem("costa-language") || "en";
let activeCategory = "all";
let query = "";
const categoryList = document.querySelector("#categoryList"),
  menuContent = document.querySelector("#menuContent");
function localName(name, lang, id) {
  if (lang === "en") return name;
  if (lang === "ku" && soraniNames[id]) return soraniNames[id];
  const map = words[lang];
  return name
    .split(/(\s+|&|[-'])/)
    .map((part) => map[part.toLowerCase()] || part)
    .join("")
    .replace(/\s*&\s*/g, " و ");
}
function productImagePath(p) {
  const folder = {
    cold: "Cold Drinks",
    desserts: "Desserts",
    shakes: "Milkshakes",
    juice: "Fresh Juice",
    hot: "Hot Drinks",
    iced: "Iced Drinks",
    signature: "Signature Drinks",
    icecream: "Ice Creams",
  }[p.category];
  return `assets/${folder}/${encodeURIComponent(p.file).replace(/%2F/gi, "/")}`;
}
function renderCategories() {
  categoryList.innerHTML = categories
    .filter(
      (c) =>
        c.id === "all" ||
        products.some((p) => p.category === c.id && matches(p)),
    )
    .map(
      (c) =>
        `<button class="category-button ${activeCategory === c.id ? "active" : ""}" role="tab" aria-selected="${activeCategory === c.id}" data-category="${c.id}">${c[currentLang]}</button>`,
    )
    .join("");
  categoryList.querySelectorAll("button").forEach((b) =>
    b.addEventListener("click", () => {
      activeCategory = b.dataset.category;
      render();
    }),
  );
}
function matches(p) {
  const n = localName(p.name, currentLang, p.id).toLowerCase();
  return !query || p.name.toLowerCase().includes(query) || n.includes(query);
}
function render() {
  renderCategories();
  let visible = products.filter(
    (p) =>
      (activeCategory === "all" || p.category === activeCategory) && matches(p),
  );
  let groups =
    activeCategory === "all"
      ? [
          "hot",
          "iced",
          "shakes",
          "juice",
          "cold",
          "signature",
          "desserts",
          "icecream",
        ]
      : [activeCategory];
  menuContent.innerHTML = groups
    .map((cat) => {
      const list = visible.filter((p) => p.category === cat);
      if (!list.length) return "";
      return `<section class="menu-group" id="group-${cat}"><div class="group-heading"><h2>${groupName[currentLang][cat]}</h2><span class="group-count">${String(list.length).padStart(2, "0")}</span><span class="group-line"></span></div><div class="product-grid">${list.map((p) => `<article class="product-card"><div class="product-image-wrap"><img class="product-image" src="${productImagePath(p)}" alt="${localName(p.name, currentLang, p.id)}" loading="lazy"></div><div class="product-info"><h3>${localName(p.name, currentLang, p.id)}</h3><span class="product-price">${p.price ? `${p.price.toLocaleString("en-US")} IQD` : `<span class="no-price">${ui[currentLang].ask}</span>`}</span></div></article>`).join("")}</div></section>`;
    })
    .join("");
  document.querySelector("#emptyState").hidden = visible.length > 0;
  document.querySelector("#resultCount").textContent =
    `${visible.length} ${ui[currentLang].items}`;
}
function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem("costa-language", lang);
  const rtl = lang === "ar" || lang === "ku";
  document.documentElement.lang = lang === "ku" ? "ckb" : lang;
  document.documentElement.dir = rtl ? "rtl" : "ltr";
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const v = ui[lang][el.dataset.i18n];
    if (v) el.innerHTML = v;
  });
  document.querySelector("#searchInput").placeholder = ui[lang].search;
  document
    .querySelector("#searchInput")
    .setAttribute("aria-label", ui[lang].search);
  render();
}
document.querySelector("#language").value = currentLang;
document
  .querySelector("#language")
  .addEventListener("change", (e) => applyLanguage(e.target.value));
document.querySelector("#searchInput").addEventListener("input", (e) => {
  query = e.target.value.trim().toLowerCase();
  render();
});
document.querySelector("#themeToggle").addEventListener("click", () => {
  document.body.classList.toggle("dark");
  const isDark = document.body.classList.contains("dark");
  localStorage.setItem("costa-theme", isDark ? "dark" : "light");
  document.querySelector("#themeIcon").textContent = isDark ? "☀" : "☾";
  document
    .querySelector("#themeToggle")
    .setAttribute(
      "aria-label",
      isDark ? "Switch to light mode" : "Switch to dark mode",
    );
  document.querySelector('meta[name="theme-color"]').content = isDark
    ? "#1c1916"
    : "#f4efe6";
});
if (localStorage.getItem("costa-theme") === "dark") {
  document.body.classList.add("dark");
  document.querySelector("#themeIcon").textContent = "☀";
}
document.addEventListener("keydown", (e) => {
  if (
    e.key === "/" &&
    !["INPUT", "TEXTAREA"].includes(document.activeElement.tagName)
  ) {
    e.preventDefault();
    document.querySelector("#searchInput").focus();
  }
  if (e.key === "Escape" && document.activeElement.id === "searchInput") {
    document.querySelector("#searchInput").value = "";
    query = "";
    render();
  }
});
applyLanguage(currentLang);
